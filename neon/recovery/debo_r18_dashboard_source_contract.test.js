'use strict';
const assert = require('node:assert/strict');
const { sourceHealth } = require('./debo_r18_dashboard_source_contract');
let tests = 0;
function test(fn) { fn(); tests++; }
const synced = {sourceReadVerified:true,taskReadsVerified:true,acceptedCount:15,importReadbackVerified:true};
const quality = {...synced,sourceFreshnessVerified:true,mobileQAPassed:true,securityQAPassed:true,ownerReleaseApproved:true};
test(() => assert.equal(sourceHealth().health,'UNKNOWN'));
test(() => assert.equal(sourceHealth({sourceReadVerified:true,taskReadsVerified:true}).eligible_for_release,false));
test(() => assert.equal(sourceHealth({sourceReadVerified:true,taskReadsVerified:true,acceptedCount:15,importReadbackVerified:false}).reason,'SYNC_NOT_VERIFIED'));
test(() => assert.equal(sourceHealth({...synced,sourceFreshnessVerified:true}).reason,'MOBILE_QA_OPEN'));
test(() => assert.equal(sourceHealth(quality).eligible_for_release,true));
test(() => assert.equal(sourceHealth({...quality,ownerReleaseApproved:false}).reason,'OWNER_RELEASE_HOLD'));
test(() => assert.equal(sourceHealth({...quality,securityQAPassed:false}).reason,'SECURITY_QA_OPEN'));
test(() => assert.equal(sourceHealth({...quality,sourceFreshnessVerified:false}).reason,'FRESHNESS_NOT_VERIFIED'));
test(() => assert.equal(sourceHealth({...quality,mobileQAPassed:false}).reason,'MOBILE_QA_OPEN'));
test(() => assert.equal(sourceHealth({...quality,acceptedCount:0}).eligible_for_release,false));
test(() => assert.equal(sourceHealth({...quality,acceptedCount:-1}).health,'UNKNOWN'));
test(() => assert.equal(sourceHealth({...quality,acceptedCount:'15'}).eligible_for_release,false));
test(() => assert.equal(sourceHealth({...quality,ownerReleaseApproved:'true'}).eligible_for_release,false));
test(() => assert.equal(sourceHealth({...quality,securityQAPassed:1}).eligible_for_release,false));
test(() => assert.equal(sourceHealth({...quality,taskReadsVerified:false}).reason,'CORE_READBACK_MISSING'));
test(() => assert.equal(sourceHealth({...quality,sourceReadVerified:false}).reason,'SOURCE_NOT_VERIFIED'));
test(() => assert.equal(sourceHealth({...quality,importReadbackVerified:false}).reason,'SYNC_NOT_VERIFIED'));
test(() => assert.equal(sourceHealth(quality).health,'VERIFIED'));
const health = sourceHealth(quality);
test(() => assert.equal(Object.isFrozen(health),true));
test(() => assert.equal(sourceHealth(quality).source,'DEBO Core'));
console.log('PASS '+tests+' fail-closed dashboard contract assertions');
