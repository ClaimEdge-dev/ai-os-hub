'use strict';
const assert=require('node:assert/strict');
const {plan,parseSheet,reconcile,hashRow,validateApproval}=require('./debo_r18_sync_plan');
const base={work_id:'WORK-TEST-001',project_id:'TEST',project_name:'Test source',objective:'Verify safe import',state:'PRIVATE / INTAKE OPEN',priority:'P1',owner:'Test owner'};
let count=0;
function test(fn){fn();count++;}
test(()=>assert.equal(plan([base]).counts.quarantine,1));
test(()=>assert.equal(plan([{...base,state:'PARKED BY OWNER / RECORDS PRESERVED'}]).counts.hold_owner,1));
test(()=>assert.equal(plan([{...base,state:'PARKED BY OWNER / RECORDS PRESERVED'}],{mappings:{'PARKED BY OWNER / RECORDS PRESERVED':{raw_state:'PARKED BY OWNER / RECORDS PRESERVED',status:'In Progress',approved_by:'Owner',approved_at:'2026-11-08T00:00:00Z'}}}).counts.hold_owner,1));
test(()=>assert.throws(()=>plan([base,base]),/Duplicate work_id/));
test(()=>assert.throws(()=>plan([{...base,work_id:''}]),/Missing work_id/));
test(()=>assert.equal(plan([{...base,priority:'P7'}]).counts.reject,1));
test(()=>assert.equal(plan([{...base,objective:''}]).counts.reject,1));
test(()=>assert.equal(plan([base],{mappings:{[base.state]:{raw_state:base.state,status:'Done'}}}).counts.quarantine,1));
test(()=>assert.equal(plan([base],{mappings:{[base.state]:{raw_state:base.state,status:'In Progress',approved_by:'owner',approved_at:'2026-11-08T00:00:00Z'}}}).counts.review_fields,1));
const verified={...base,assignee_role:'Proof',pillar:'SYSTEMS'};
const approval={mappings:{[base.state]:{raw_state:base.state,status:'Review',approved_by:'owner',approved_at:'2026-11-08T00:00:00Z'}}};
test(()=>assert.equal(plan([verified],approval).counts.accept,1));
test(()=>assert.equal(plan([verified],approval).entries[0].provenance.raw_source_state,base.state));
test(()=>assert.equal(plan([verified],approval).write_eligible,false));
test(()=>assert.equal(hashRow(verified),hashRow({...verified})));
test(()=>assert.equal(reconcile([],plan([base]))[0].operation,'STAGE_NEW'));
const p=plan([base]); const history=[{work_id:base.work_id,source_row_hash:p.entries[0].provenance.source_row_hash}];
test(()=>assert.equal(reconcile(history,p)[0].operation,'NOOP'));
test(()=>assert.equal(reconcile([{...history[0],source_row_hash:'changed'}],p)[0].operation,'CONFLICT_REVIEW'));
test(()=>assert.equal(validateApproval({raw_state:base.state,status:'Review',approved_by:'',approved_at:'2026-11-08T00:00:00Z'},base.state),false));
test(()=>assert.equal(parseSheet([['work_id','project_id','project_name','objective','state','priority','owner'],['x','p','t','o','s','P2','u']]).length,1));
test(()=>assert.throws(()=>parseSheet([['work_id'],['x']]),/Missing column/));
test(()=>assert.equal(plan([base]).entries[0].status,null));
console.log('PASS '+count+' nonproduction planner assertions');
